//
// In the NVIDIA CUDA build, these functions are auto-generated by nvcc from
// the .cu kernel files and are called by createPxg*() to force static linkage
// of the GPU kernel modules.
//
// On HCU, kernels are loaded dynamically via hipModuleLoad() and resolved at
// runtime by the KernelWrangler.  The init*Kernels*() registration is not
// needed — but the host-side .cpp files still call them from createPxg*().
// We provide empty stubs so the host-side code compiles and links unchanged.

